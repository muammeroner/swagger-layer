import * as fs from "node:fs";
import * as path from "node:path";
import { parseArgs, readConfig, resolveConfigFilePath } from "./config.js";
import { generateEnums } from "./generators/enums.js";
import {
  generateModuleApi,
  generateModuleIndex,
  generateModuleRepository,
  generateModuleService,
  generateRootIndex,
} from "./generators/module.js";
import { generateTypes } from "./generators/types.js";
import { extractSchemas, loadSwagger, parseOperations } from "./parser.js";
import type { CliArgs, GenerateOptions, SwaggerLayerConfig } from "./types.js";
import { getEnumSchemaNames, isModuleExcluded, toKebabCase } from "./utils.js";

export interface GenerateResult {
  config: SwaggerLayerConfig;
  outputDir: string;
  generatedFiles: string[];
  modules: string[];
}

/** Environment variables that can override the project root (newest name first). */
const PROJECT_ROOT_ENV_VARS = [
  "SWAGGER_LAYER_PROJECT_ROOT",
  "SWAGGER_FLOW_PROJECT_ROOT",
  "REACT_SWAGGEN_PROJECT_ROOT",
];

const LEGACY_GENERATED_FILES = ["http.ts", "interfaces.ts"];
const LEGACY_HEADER_PREFIX = "// Auto-generated by ";

const isRemoteUrl = (value: string): boolean => /^https?:\/\//i.test(value);

function resolveProjectRoot(cwd?: string): string {
  const fromEnv = PROJECT_ROOT_ENV_VARS.map((name) => process.env[name]).find(Boolean);
  return path.resolve(cwd || fromEnv || process.cwd());
}

function resolveSwaggerInput(
  root: string,
  config: SwaggerLayerConfig,
  args: CliArgs
): { swaggerUrl: string; file?: string } {
  const fromTemplate = (name: string) => ({
    swaggerUrl: config.swaggerUrlTemplate.replaceAll("{name}", name),
  });
  const fromFile = (filePath: string) => ({ swaggerUrl: filePath, file: filePath });

  if (args.url) return { swaggerUrl: args.url };
  if (args.file) return fromFile(path.resolve(root, args.file));
  if (args.name) return fromTemplate(args.name);

  if (config.input) {
    if (isRemoteUrl(config.input)) return { swaggerUrl: config.input };
    const resolvedInput = path.resolve(root, config.input);
    if (fs.existsSync(resolvedInput)) return fromFile(resolvedInput);
  }

  const defaultLocalSwagger = path.resolve(root, "swagger.json");
  if (fs.existsSync(defaultLocalSwagger)) return fromFile(defaultLocalSwagger);

  return fromTemplate(config.defaultName);
}

/** Removes files produced by older versions, but only if they were auto-generated. */
function cleanupLegacyGeneratedFiles(outputDir: string): void {
  for (const legacyFile of LEGACY_GENERATED_FILES) {
    const legacyPath = path.join(outputDir, legacyFile);
    if (!fs.existsSync(legacyPath)) continue;
    const head = fs.readFileSync(legacyPath, "utf8").slice(0, 120);
    if (head.startsWith(LEGACY_HEADER_PREFIX)) {
      fs.rmSync(legacyPath, { force: true });
    }
  }
}

function removeExcludedModuleDirs(outputDir: string, config: SwaggerLayerConfig): void {
  for (const ex of config.excludedModules) {
    const slug = toKebabCase(ex);
    const exDir = path.join(outputDir, slug);
    if (fs.existsSync(exDir)) {
      fs.rmSync(exDir, { recursive: true, force: true });
      console.log(`✓ Removed excluded module directory: ${config.exportPath}/${slug}`);
    }
  }
}

function logSummary(
  configPath: string | undefined,
  swaggerUrl: string,
  config: SwaggerLayerConfig
): void {
  console.log(`=== [swagger-layer] Generating TypeScript API Layer ===`);
  console.log(`Config File : ${configPath || "(default)"}`);
  console.log(`Source      : ${swaggerUrl}`);
  console.log(`Export Path : ${config.exportPath}`);
  console.log(`HTTP Client : ${config.httpClient}`);
  console.log(`Prefix      : ${config.prefix || "(none)"}`);
  console.log(`Base URL    : ${config.baseUrl}`);
  console.log(`API Version : ${config.version}`);
}

export async function generateApi(options: GenerateOptions = {}): Promise<GenerateResult> {
  const root = resolveProjectRoot(options.cwd);
  const args = options.args || parseArgs();
  const configPath = resolveConfigFilePath(root, args.config);
  const config = readConfig(root, args, options.config);
  const outputDir = path.resolve(root, config.exportPath);

  const { swaggerUrl, file } = resolveSwaggerInput(root, config, args);
  logSummary(configPath, swaggerUrl, config);

  const { doc } = await loadSwagger(swaggerUrl, file);
  if (!doc?.paths || typeof doc.paths !== "object") {
    throw new Error("Invalid Swagger/OpenAPI document: 'paths' object is missing");
  }

  const schemas = extractSchemas(doc);
  const enums = new Set(getEnumSchemaNames(schemas));
  console.log(
    `Discovered ${enums.size} enums and ${Object.keys(schemas).length - enums.size} schemas.`
  );

  const { modules, opResponses } = parseOperations(doc, enums, config.excludedModules);

  fs.mkdirSync(outputDir, { recursive: true });
  cleanupLegacyGeneratedFiles(outputDir);

  const generatedFiles: string[] = [];
  const writeOut = (relPath: string, content: string): void => {
    const fullPath = path.join(outputDir, relPath);
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, content, "utf-8");
    generatedFiles.push(fullPath);
  };

  // 1. Shared enums & types
  writeOut("enums.ts", generateEnums(schemas));
  console.log(`✓ Generated ${config.exportPath}/enums.ts`);

  writeOut("types.ts", generateTypes(schemas, enums, opResponses));
  console.log(`✓ Generated ${config.exportPath}/types.ts`);

  // 2. Drop directories of modules that are now excluded
  removeExcludedModuleDirs(outputDir, config);

  // 3. Per-module api.ts, repository.ts, service.ts, index.ts
  const moduleSlugs: string[] = [];
  for (const [moduleSlug, { tag, methods }] of modules) {
    if (isModuleExcluded(moduleSlug, config.excludedModules)) continue;
    moduleSlugs.push(moduleSlug);

    const moduleFiles: Record<string, string> = {
      "api.ts": generateModuleApi(methods, enums, config),
      "repository.ts": generateModuleRepository(tag, methods, enums, config),
      "service.ts": generateModuleService(tag, methods, enums, config),
      "index.ts": generateModuleIndex(),
    };
    for (const [fileName, content] of Object.entries(moduleFiles)) {
      writeOut(path.join(moduleSlug, fileName), content);
    }

    console.log(`✓ Generated ${config.exportPath}/${moduleSlug} (${methods.length} operations)`);
  }

  // 4. Root barrel
  writeOut("index.ts", generateRootIndex(moduleSlugs));
  console.log(`✓ Generated ${config.exportPath}/index.ts`);
  console.log(`✓ Swagger Layer - API Generation Complete \n`);

  return {
    config,
    outputDir,
    generatedFiles,
    modules: moduleSlugs,
  };
}
