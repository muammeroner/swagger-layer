import type { OpenApiSchema } from "../types.js";
import { formatPropertyKey } from "../utils.js";

export function generateEnums(
  schemas: Record<string, OpenApiSchema>,
  sourceUrl: string
): string {
  const enumNames = Object.keys(schemas)
    .filter((k) => Array.isArray(schemas[k].enum))
    .sort();

  let code = `// Auto-generated by swagger-layer from "./swagger.json"\n\n`;

  if (enumNames.length === 0) {
    return `${code}export {};\n`;
  }

  for (const name of enumNames) {
    const schema = schemas[name];
    const items = schema.enum || [];
    if (schema.description) {
      code += `/** ${schema.description} */\n`;
    }
    code += `export enum E${name} {\n`;
    for (let i = 0; i < items.length; i++) {
      const member = formatPropertyKey(String(items[i]));
      code += i === 0 ? `  ${member} = 1,\n` : `  ${member},\n`;
    }
    code += `}\n\n`;
  }

  return code.trimEnd() + "\n";
}
