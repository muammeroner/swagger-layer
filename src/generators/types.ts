import { extractSchemas, schemaToTsType } from "../parser.js";
import type { OpenApiDocument, OpenApiSchema, OperationResponseInfo } from "../types.js";
import { formatPropertyKey } from "../utils.js";

function renderInterfaceProperties(
  schema: OpenApiSchema | undefined,
  enums: Set<string>,
  allSchemas: Record<string, OpenApiSchema>
): string {
  if (!schema?.properties) return "";
  const requiredSet = new Set(schema.required || []);
  let propsCode = "";

  for (const [propName, propSchema] of Object.entries(schema.properties)) {
    const tsType = schemaToTsType(propSchema, enums, allSchemas);
    const optionalFlag = requiredSet.has(propName) ? "" : "?";
    propsCode += `  ${formatPropertyKey(propName)}${optionalFlag}: ${tsType};\n`;
  }

  return propsCode;
}

export function generateTypes(
  doc: OpenApiDocument,
  enums: Set<string>,
  opResponses: Map<string, OperationResponseInfo>,
  hasErrorListSchema: boolean,
  sourceUrl: string
): string {
  const schemas = extractSchemas(doc);
  const schemaNames = Object.keys(schemas)
    .filter((k) => !schemas[k].enum)
    .sort();

  const sortedEnumNames = Array.from(enums)
    .map((e) => `E${e}`)
    .sort();

  let code = `// Auto-generated by swagger-layer from "./swagger.json"\n`;
  if (sortedEnumNames.length > 0) {
    code += `import type { ${sortedEnumNames.join(", ")} } from "./enums";\n`;
  }
  code += `\n`;

  code += `export type HttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n\n`;

  code += `export type PrimitiveQueryValue = string | number | boolean | null | undefined;\n`;
  code += `export type QueryParamValue = PrimitiveQueryValue | PrimitiveQueryValue[];\n`;
  code += `export type QueryParamsRecord = Record<string, unknown>;\n\n`;

  const errorListType = hasErrorListSchema
    ? "ErrorList[]"
    : "Array<{ message?: string; code?: string; field?: string }>";

  code += `/**\n * Standard API Error payload structure.\n */\n`;
  code += `export interface ApiErrorResponse {\n`;
  code += `  type?: string;\n`;
  code += `  title?: string;\n`;
  code += `  status?: number;\n`;
  code += `  detail?: string;\n`;
  code += `  instance?: string;\n`;
  code += `  success?: boolean;\n`;
  code += `  statusCode?: number;\n`;
  code += `  result?: string;\n`;
  code += `  correlationId?: string;\n`;
  code += `  errorList?: ${errorListType};\n`;
  code += `}\n\n`;

  code += `/**\n * Per-request configuration compatible with the MDN Fetch API and React AbortController.\n */\n`;
  code += `export interface RequestConfig {\n`;
  code += `  baseUrl?: string;\n`;
  code += `  query?: object;\n`;
  code += `  defaultHeaders?: Record<string, string>;\n`;
  code += `  headers?: Record<string, string>;\n`;
  code += `  /** AbortSignal for cancelling in-flight requests inside React useEffect cleanup */\n`;
  code += `  signal?: AbortSignal;\n`;
  code += `  credentials?: RequestCredentials;\n`;
  code += `  cache?: RequestCache;\n`;
  code += `  mode?: RequestMode;\n`;
  code += `}\n\n`;

  code += `export interface HttpRequestArgs<TBody = unknown> {\n`;
  code += `  path: string;\n`;
  code += `  pathParams?: Record<string, string | number>;\n`;
  code += `  body?: TBody;\n`;
  code += `  options?: RequestConfig;\n`;
  code += `}\n\n`;

  const generatedInterfaceNames = new Set<string>([
    "ApiErrorResponse",
    "RequestConfig",
    "HttpRequestArgs",
  ]);

  // 1. Generate OpenAPI schema interfaces
  for (const name of schemaNames) {
    const schema = schemas[name];
    generatedInterfaceNames.add(name);
    if (schema.description) {
      code += `/** ${schema.description} */\n`;
    }
    code += `export interface ${name} {\n`;
    code += renderInterfaceProperties(schema, enums, schemas);
    code += `}\n\n`;
  }

  // 2. Generate inline operation response interfaces
  for (const [respName, { schema, refName }] of opResponses.entries()) {
    if (generatedInterfaceNames.has(respName)) continue;
    generatedInterfaceNames.add(respName);

    const targetSchema = refName && schemas[refName] ? schemas[refName] : schema;
    code += `export interface ${respName} {\n`;
    code += renderInterfaceProperties(targetSchema, enums, schemas);
    code += `}\n\n`;
  }

  return code.trimEnd() + "\n";
}
